"""SQLite model → PostgreSQL DDL.

The rules, in one place (docs/postgres-etl.md has the reasoning):

  types       INTEGER→bigint · REAL→double precision · TEXT→text · BLOB→bytea
              BLOB `embedding` (1536 float32) → vector(1536) (pgvector), or real[] when
              the extension is missing (reported, no index built)
              TEXT holding only JSON documents → jsonb (detected from the data)
              ISO-timestamp TEXT stays text in this phase (111 columns, 7 formats)
  identity    single INTEGER PRIMARY KEY → bigint GENERATED BY DEFAULT AS IDENTITY
  generated   VIRTUAL → STORED; json_extract(col,'$.a.b') → (col #>> '{a,b}') with
              bcc_to_num()/bcc_to_int() around numeric targets (SQLite affinity rules);
              the ~12 KB source_host CASE tree → bcc_source_host(url)
  fts5        → one `fts tsvector` column per recipe table, weights A name+dish ·
              B author+domain · C ingredients · D cuisine, GIN index, BEFORE trigger
  vec0        dissolves: HNSW cosine index directly on the base table's embedding
  bcc_sortkey the Python-registered sort fold → an IMMUTABLE SQL function
  triggers    fts (ported), vec cleanup (unneeded) — the SQLite ones are not carried
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

from .sqlite_schema import Column, Index, Schema, Table

EMBED_DIM = 1536
FTS_TABLES = ("recipes", "master_recipes")
HNSW_TABLES = ("dishes", "master_recipes", "products")   # the three that had vec0 indexes

_TYPE_MAP = {
    "INTEGER": "bigint",
    "INT": "bigint",
    "BOOLEAN": "bigint",
    "REAL": "double precision",
    "FLOAT": "double precision",
    "DOUBLE": "double precision",
    "NUMERIC": "double precision",
    "TEXT": "text",
    "BLOB": "bytea",
    "": "text",
    "ANY": "text",
}


def q(ident: str) -> str:
    """Quote an identifier. Every identifier in recipes.db is lower-case, so quoting
    changes nothing for unquoted app SQL; it only guards reserved words."""
    return '"' + ident.replace('"', '""') + '"'


def is_embedding(col: Column) -> bool:
    return col.name == "embedding" and col.base_type == "BLOB"


def pg_type(table: Table, col: Column, *, vector_ok: bool) -> str:
    if is_embedding(col):
        return f"vector({EMBED_DIM})" if vector_ok else "real[]"
    if col.name in table.json_columns:
        return "jsonb"
    try:
        return _TYPE_MAP[col.base_type]
    except KeyError:
        raise ValueError(f"{table.name}.{col.name}: no mapping for declared type {col.decl!r}")


# --------------------------------------------------------------------------- expressions

_JSON_EXTRACT = re.compile(r"json_extract\(\s*(\w+)\s*,\s*'\$((?:\.\w+|\[\d+\])*)'\s*\)", re.I)


def json_path(path: str) -> str:
    """'$._match.candidates[0].dish' (without the '$') → '{_match,candidates,0,dish}'."""
    parts = []
    for key, idx in re.findall(r"\.(\w+)|\[(\d+)\]", path):
        parts.append(key if key else idx)
    return "{" + ",".join(parts) + "}"


def translate_expr(expr: str, *, numeric: str | None = None) -> str:
    """Rewrite a SQLite expression for PostgreSQL.

    numeric: None for text results; 'bcc_to_num' / 'bcc_to_int' wraps each
    json_extract so the result carries SQLite's REAL / INTEGER affinity.
    """
    def repl(m):
        col, path = m.group(1), m.group(2)
        acc = f"({q(col)} #>> '{json_path(path)}')"
        return f"{numeric}({acc})" if numeric else acc

    out = _JSON_EXTRACT.sub(repl, expr)
    out = re.sub(r"\binstr\(", "strpos(", out, flags=re.I)
    out = re.sub(r"\bifnull\(", "coalesce(", out, flags=re.I)
    return out


# The one expression too tangled to translate mechanically. SQLite: strip the
# scheme, cut at the first '/', cut at the first '?', drop a leading 'www.',
# lower-case. bcc_source_host (below) does the same four steps.
GENERATED_OVERRIDES = {
    "source_host": "bcc_source_host((\"data\" #>> '{_source,originalUrl}'))",
}


def generated_expr(col: Column) -> str:
    if col.name in GENERATED_OVERRIDES:
        return GENERATED_OVERRIDES[col.name]
    numeric = {"REAL": "bcc_to_num", "INTEGER": "bcc_to_int"}.get(col.base_type)
    return translate_expr(col.gen_expr or "", numeric=numeric)


# --------------------------------------------------------------------------- DDL pieces

FUNCTIONS_SQL = r"""
CREATE OR REPLACE FUNCTION bcc_to_num(x text) RETURNS double precision
LANGUAGE plpgsql IMMUTABLE PARALLEL SAFE AS $$
BEGIN
  IF x IS NULL THEN RETURN NULL; END IF;
  IF x = 'true' THEN RETURN 1; END IF;
  IF x = 'false' THEN RETURN 0; END IF;
  RETURN x::double precision;
EXCEPTION WHEN others THEN
  RETURN NULL;
END $$;

CREATE OR REPLACE FUNCTION bcc_to_int(x text) RETURNS bigint
LANGUAGE plpgsql IMMUTABLE PARALLEL SAFE AS $$
DECLARE n double precision;
BEGIN
  n := bcc_to_num(x);
  IF n IS NULL OR n <> trunc(n) THEN RETURN NULL; END IF;
  RETURN n::bigint;
END $$;

-- source_host: scheme stripped, cut at '/', cut at '?', leading www. dropped, lower-cased.
CREATE OR REPLACE FUNCTION bcc_source_host(u text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT lower(CASE WHEN s.h LIKE 'www.%' THEN substr(s.h, 5) ELSE s.h END)
  FROM (
    SELECT split_part(split_part(
             CASE WHEN strpos(u, '://') > 0 THEN substr(u, strpos(u, '://') + 3) ELSE u END,
           '/', 1), '?', 1) AS h
  ) s
$$;

-- bcc_sortkey: the server's _sort_key_fold (NFKD accent strip + typographic
-- punctuation to ASCII + casefold). unaccent stands in for the NFKD strip; it is
-- STABLE by declaration but constant in practice, so wrapping it IMMUTABLE is the
-- usual idiom and lets the function sit in an index later.
CREATE OR REPLACE FUNCTION bcc_sortkey(s text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT lower(public.unaccent('public.unaccent',
           translate(s,
                     chr(8216)||chr(8217)||chr(8220)||chr(8221)||chr(8211)||chr(8212)||chr(8722)||chr(160),
                     '''''' || '""---' || ' ')))
$$;
"""

FTS_SETUP_SQL = r"""
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_ts_config WHERE cfgname = 'bcc') THEN
    CREATE TEXT SEARCH CONFIGURATION bcc ( COPY = english );
    ALTER TEXT SEARCH CONFIGURATION bcc
      ALTER MAPPING FOR hword, hword_part, word, asciiword, asciihword, hword_asciipart
      WITH unaccent, english_stem;
  END IF;
END $$;

-- The fts5 row, as a weighted tsvector. Columns → weights: name, dish → A;
-- author, domain → B; ingredients → C; cuisine → D. The domain text repeats the
-- SQLite trigger: host, host with dots as spaces, the domain's display name,
-- the page's siteName.
CREATE OR REPLACE FUNCTION bcc_recipe_fts(data jsonb, host text, display_name text) RETURNS tsvector
LANGUAGE sql STABLE AS $$
  SELECT setweight(to_tsvector('bcc', coalesce(data #>> '{name}', '')), 'A')
      || setweight(to_tsvector('bcc', coalesce(data #>> '{_identity,likelyDish}', '')), 'A')
      || setweight(to_tsvector('bcc', coalesce(data #>> '{author,name}', '')), 'B')
      || setweight(to_tsvector('bcc', concat_ws(' ', host, replace(coalesce(host, ''), '.', ' '),
                                                display_name, data #>> '{_source,siteName}')), 'B')
      -- '/' → ' ' : fts5's unicode61 splits "vegetable/chicken" into two words;
      -- Postgres' parser would keep it as one `file` token and miss "chicken".
      || setweight(to_tsvector('bcc', coalesce((
             SELECT translate(string_agg(x, ' '), '/', ' ')
             FROM jsonb_array_elements_text(
                    CASE WHEN jsonb_typeof(data -> 'recipeIngredient') = 'array'
                         THEN data -> 'recipeIngredient' ELSE '[]'::jsonb END) AS x), '')), 'C')
      || setweight(to_tsvector('bcc', coalesce(data #>> '{_identity,cuisine}', '')), 'D')
$$;

CREATE OR REPLACE FUNCTION bcc_recipe_fts_trg() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE h text; dn text;
BEGIN
  h := bcc_source_host(NEW.data #>> '{_source,originalUrl}');
  SELECT display_name INTO dn FROM domains WHERE domain = h;
  NEW.fts := bcc_recipe_fts(NEW.data, h, dn);
  RETURN NEW;
END $$;
"""


def fts_table_sql(table: str) -> list[str]:
    return [
        f"DROP TRIGGER IF EXISTS {table}_fts_biu ON {q(table)}",
        f"CREATE TRIGGER {table}_fts_biu BEFORE INSERT OR UPDATE OF data ON {q(table)} "
        f"FOR EACH ROW EXECUTE FUNCTION bcc_recipe_fts_trg()",
        f"UPDATE {q(table)} t SET fts = bcc_recipe_fts(t.data, t.source_host, "
        f"(SELECT d.display_name FROM domains d WHERE d.domain = t.source_host))",
        f"CREATE INDEX IF NOT EXISTS {table}_fts_gin ON {q(table)} USING gin (fts)",
    ]


def column_sql(table: Table, col: Column, *, vector_ok: bool, warnings: list[str]) -> str:
    typ = pg_type(table, col, vector_ok=vector_ok)
    if col.generated:
        return f"{q(col.name)} {typ} GENERATED ALWAYS AS ({generated_expr(col)}) STORED"
    bits = [q(col.name)]
    if table.integer_pk == col.name:
        bits.append("bigint GENERATED BY DEFAULT AS IDENTITY")
    else:
        bits.append(typ)
        if col.notnull:
            bits.append("NOT NULL")
        if col.default is not None:
            d = col.default
            if typ == "jsonb" and d.strip() in ("''", '""'):
                warnings.append(f"{table.name}.{col.name}: DEFAULT '' dropped on a jsonb column")
            else:
                bits.append(f"DEFAULT {d}")
    return " ".join(bits)


def table_sql(table: Table, *, vector_ok: bool, warnings: list[str]) -> str:
    lines = [column_sql(table, c, vector_ok=vector_ok, warnings=warnings) for c in table.columns]
    if table.name in FTS_TABLES:
        lines.append('"fts" tsvector')
    if table.pk:
        lines.append("PRIMARY KEY (" + ", ".join(q(c) for c in table.pk) + ")")
    for u in table.uniques:
        lines.append("UNIQUE (" + ", ".join(q(c) for c in u) + ")")
    for chk in table.checks:
        lines.append(f"CHECK ({translate_expr(chk)})")
    body = ",\n  ".join(lines)
    return f"CREATE TABLE {q(table.name)} (\n  {body}\n)"


def index_sql(ix: Index) -> str:
    parts = []
    for p in ix.parts:
        desc = ""
        m = re.match(r"^(.*?)\s+(ASC|DESC)$", p, re.I)
        if m:
            p, desc = m.group(1), " " + m.group(2).upper()
        if re.fullmatch(r"\w+", p):
            parts.append(q(p) + desc)
        else:
            parts.append("(" + translate_expr(p) + ")" + desc)
    s = f"CREATE {'UNIQUE ' if ix.unique else ''}INDEX {q(ix.name)} ON {q(ix.table)} ({', '.join(parts)})"
    if ix.where:
        s += " WHERE " + translate_expr(ix.where)
    return s


def hnsw_sql(table: str) -> str:
    return (f"CREATE INDEX IF NOT EXISTS {table}_embedding_hnsw ON {q(table)} "
            f"USING hnsw (embedding vector_cosine_ops)")


@dataclass
class Plan:
    vector_ok: bool
    tables: list[str]
    json_columns: dict[str, list[str]]
    embedding_columns: list[str]
    skipped: dict[str, str]
    warnings: list[str] = field(default_factory=list)
    create_tables: list[str] = field(default_factory=list)
    create_indexes: list[str] = field(default_factory=list)
    post_load: list[str] = field(default_factory=list)   # fts fill + triggers + hnsw


def build_plan(schema: Schema, *, vector_ok: bool) -> Plan:
    plan = Plan(vector_ok=vector_ok, tables=[], json_columns={}, embedding_columns=[], skipped={})
    for t in schema.tables.values():
        if t.kind != "base":
            plan.skipped[t.name] = {
                "fts": "fts5 index -> tsvector column on the base table",
                "vec": "vec0 index -> embedding column + HNSW on the base table",
                "shadow": "internal storage of a virtual table",
                "virtual": "virtual table (not carried)",
            }[t.kind]
            continue
        plan.tables.append(t.name)
        if t.json_columns:
            plan.json_columns[t.name] = sorted(t.json_columns)
        for c in t.columns:
            if is_embedding(c):
                plan.embedding_columns.append(f"{t.name}.{c.name}")
        plan.create_tables.append(table_sql(t, vector_ok=vector_ok, warnings=plan.warnings))
    plan.create_indexes = [index_sql(ix) for ix in schema.indexes]
    for t in FTS_TABLES:
        if t in schema.tables:
            plan.post_load.extend(fts_table_sql(t))
    if vector_ok:
        for t in HNSW_TABLES:
            if t in schema.tables:
                plan.post_load.append(hnsw_sql(t))
    else:
        plan.warnings.append("pgvector not available: embeddings land as real[] and no HNSW index is built")
    return plan


def plan_text(plan: Plan) -> str:
    out = []
    out.append(f"vector extension: {'yes' if plan.vector_ok else 'NO (real[] fallback)'}")
    out.append(f"tables to create: {len(plan.tables)}")
    out.append(f"indexes to create: {len(plan.create_indexes)}")
    out.append("jsonb columns:")
    for t, cols in sorted(plan.json_columns.items()):
        out.append(f"  {t}: {', '.join(cols)}")
    out.append("embedding columns: " + ", ".join(plan.embedding_columns))
    out.append("not carried:")
    for name, why in sorted(plan.skipped.items()):
        out.append(f"  {name}: {why}")
    for w in plan.warnings:
        out.append("WARNING " + w)
    return "\n".join(out)
