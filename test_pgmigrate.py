"""pgmigrate unit tests — the pure pieces, no Postgres needed.
Run: python test_pgmigrate.py   (or pytest)
"""
import sqlite3

from pgmigrate import sqlite_schema as ss
from pgmigrate import translate as tr


def test_json_path():
    assert tr.json_path("._scoring.ouScore") == "{_scoring,ouScore}"
    assert tr.json_path("._match.candidates[0].dish") == "{_match,candidates,0,dish}"
    assert tr.json_path(".id") == "{id}"


def test_translate_expr_text_and_numeric():
    e = "NULLIF(TRIM(COALESCE(json_extract(data,'$._identity.cuisine'),'')),'')"
    assert tr.translate_expr(e) == "NULLIF(TRIM(COALESCE((\"data\" #>> '{_identity,cuisine}'),'')),'')"
    e = "json_extract(data,'$._scoring.domainAuthority') + json_extract(data,'$._scoring.pageAuthority')"
    out = tr.translate_expr(e, numeric="bcc_to_num")
    assert out == ("bcc_to_num((\"data\" #>> '{_scoring,domainAuthority}')) + "
                   "bcc_to_num((\"data\" #>> '{_scoring,pageAuthority}'))")
    assert tr.translate_expr("instr(x,'/') > 0") == "strpos(x,'/') > 0"


def test_balanced_and_split():
    s = "f(a, g('x,(y)', b), c)"
    assert ss._balanced(s, 1) == len(s)
    assert ss._split_top_level("a, g('x,(y)', b), c DESC") == ["a", "g('x,(y)', b)", "c DESC"]


def test_parse_index():
    name, table, unique, parts, where = ss.parse_index(
        "CREATE UNIQUE INDEX uniq_recipes_url_user ON recipes(url_normalized, user_id) WHERE url_normalized != ''")
    assert (name, table, unique) == ("uniq_recipes_url_user", "recipes", True)
    assert parts == ["url_normalized", "user_id"]
    assert where == "url_normalized != ''"
    name, table, unique, parts, where = ss.parse_index(
        "CREATE INDEX idx_recipe_json_id\nON recipes (json_extract(data, '$.id'))")
    assert parts == ["json_extract(data, '$.id')"] and where is None
    ix = ss.Index(name, table, unique, "", parts, where)
    assert tr.index_sql(ix) == "CREATE INDEX \"idx_recipe_json_id\" ON \"recipes\" (((\"data\" #>> '{id}')))"


def _mini_db():
    c = sqlite3.connect(":memory:")
    c.executescript("""
        CREATE TABLE recipes (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            recipe_id TEXT UNIQUE NOT NULL,
            data TEXT NOT NULL,
            embedding BLOB,
            notes TEXT DEFAULT '',
            ou_score REAL GENERATED ALWAYS AS (json_extract(data,'$._scoring.ouScore')) VIRTUAL,
            recipe_name TEXT GENERATED ALWAYS AS (NULLIF(TRIM(COALESCE(json_extract(data,'$.name'),'')),'')) VIRTUAL,
            source_host TEXT GENERATED ALWAYS AS (lower(json_extract(data,'$._source.originalUrl'))) VIRTUAL
        );
        CREATE TABLE dish_rejects (id INTEGER PRIMARY KEY, status TEXT CHECK (status IN ('new', 'recovered')));
        CREATE INDEX idx_hot ON recipes(ou_score DESC) WHERE ou_score >= 1;
        CREATE VIRTUAL TABLE recipes_fts USING fts5(name, dish);
        INSERT INTO recipes(recipe_id, data) VALUES ('a', '{"name":"A","_scoring":{"ouScore":1.5}}');
        INSERT INTO recipes(recipe_id, data) VALUES ('b', '{"name":"B"}');
    """)
    return c


def test_introspect_and_ddl():
    c = _mini_db()
    schema = ss.introspect(c)
    kinds = {t.name: t.kind for t in schema.tables.values()}
    assert kinds["recipes"] == "base" and kinds["recipes_fts"] == "fts"
    assert all(k == "shadow" for n, k in kinds.items() if n.startswith("recipes_fts_"))
    t = schema.tables["recipes"]
    assert t.integer_pk == "id" and t.autoincrement
    assert t.uniques == [["recipe_id"]]
    assert t.json_columns == {"data"}
    assert t.col("ou_score").gen_expr == "json_extract(data,'$._scoring.ouScore')"
    assert schema.tables["dish_rejects"].checks == ["status IN ('new', 'recovered')"]
    warnings = []
    ddl = tr.table_sql(t, vector_ok=True, warnings=warnings)
    assert '"id" bigint GENERATED BY DEFAULT AS IDENTITY' in ddl
    assert '"data" jsonb NOT NULL' in ddl
    assert '"embedding" vector(1536)' in ddl
    assert "\"ou_score\" double precision GENERATED ALWAYS AS (bcc_to_num((\"data\" #>> '{_scoring,ouScore}'))) STORED" in ddl
    assert "\"source_host\" text GENERATED ALWAYS AS (bcc_source_host((\"data\" #>> '{_source,originalUrl}'))) STORED" in ddl
    assert '"fts" tsvector' in ddl and 'PRIMARY KEY ("id")' in ddl and 'UNIQUE ("recipe_id")' in ddl
    assert warnings == []
    [ix] = schema.indexes
    assert tr.index_sql(ix) == 'CREATE INDEX "idx_hot" ON "recipes" ("ou_score" DESC) WHERE ou_score >= 1'
    plan = tr.build_plan(schema, vector_ok=False)
    assert "real[]" in plan.create_tables[0] or any("real[]" in s for s in plan.create_tables)
    assert any("pgvector not available" in w for w in plan.warnings)


def test_source_host_semantics_mirror():
    """The SQLite expression's four steps, mirrored in Python, against cases the
    SQL function must reproduce (checked live by verify.py over every row)."""
    def host(u):
        if u is None:
            return None
        s1 = u[u.index("://") + 3:] if "://" in u else u
        h = s1.split("/", 1)[0]
        h = h.split("?", 1)[0]
        return (h[4:] if h.startswith("www.") else h).lower()
    assert host("https://www.Example.com/a/b") == "example.com"
    assert host("example.com") == "example.com"
    assert host("http://host?x=1") == "host"
    assert host("ftp://") == ""
    assert host(None) is None


